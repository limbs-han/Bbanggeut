-- 카메라마다 "감지를 켤지" 스위치를 둔다.
--
-- **왜 필요한가**: 지금까지 끌 수 있는 것은 알림뿐이었다. 알림을 꺼도 기기는
-- 그대로 찍어 올리고 서버는 그대로 저장했다 — 손님이 왔거나 잠시 찍히고 싶지
-- 않을 때 쓸 수 있는 것이 없었다.
--
-- **왜 금고가 아니라 기기 단위인가**: 사람은 "거실 카메라만 끄고 싶다"로
-- 생각한다. 금고 단위로 두면 카메라가 둘 이상인 집에서 하나를 끄려고 전부를
-- 꺼야 한다. 금고 전체를 끄는 것은 카메라를 하나씩 끄는 것으로 표현된다.
--
-- **기본값이 true인 이유**: 이미 쓰고 있는 카메라가 마이그레이션 한 번으로
-- 조용히 꺼지면, 사용자에게는 "그날부터 아무것도 안 찍혔다"로 보인다.
ALTER TABLE devices
    ADD COLUMN IF NOT EXISTS detection_enabled boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN devices.detection_enabled IS
    '감지·저장 스위치. false면 백엔드가 이 기기의 영상 업로드를 거절한다. '
    '기기는 여전히 찍고 올리려 시도한다 — 펌웨어를 바꾸지 않는 서버 측 차단이다.';

-- 인덱스를 두지 않는다. 이 값은 업로드 경로에서 기기 행을 이미 집은 뒤에 보는
-- 값이고, "꺼진 기기 목록"을 훑는 질의는 없다.
